create or replace function public.send_session_message(p_session_id bigint, p_body text)
returns jsonb language plpgsql security definer set search_path = public as $$
declare caller uuid := auth.uid(); result public.session_messages;
begin
  if char_length(trim(coalesce(p_body, ''))) not between 1 and 6000 then raise exception 'invalid_message'; end if;
  if not exists (select 1 from public.sessions s where s.id = p_session_id and caller in (s.mentor_id, s.mentee_id)) then
    raise exception 'not_found';
  end if;
  insert into public.session_messages(session_id, sender_id, kind, body)
  values (p_session_id, caller, 'message', trim(p_body)) returning * into result;
  return to_jsonb(result);
end;
$$;
revoke all on function public.send_session_message(bigint, text) from public, anon;
grant execute on function public.send_session_message(bigint, text) to authenticated;

create or replace function public.pm_set_outbound_message(p_session_id bigint, p_message text)
returns jsonb language plpgsql security definer set search_path = public as $$
declare caller uuid := auth.uid(); session_row public.sessions;
begin
  if caller is null then raise exception 'auth_required'; end if;
  if char_length(trim(coalesce(p_message, ''))) not between 1 and 6000 then raise exception 'invalid_outbound_message'; end if;
  select * into session_row from public.sessions where id = p_session_id for update;
  if not found or session_row.mentee_id <> caller then raise exception 'not_allowed'; end if;
  update public.sessions set outbound_message = trim(p_message), last_activity_at = now() where id = p_session_id;
  insert into public.session_messages(session_id, sender_id, kind, body, created_at)
  values (p_session_id, caller, 'request', trim(p_message), session_row.created_at)
  on conflict do nothing;
  insert into public.audit_logs(actor_id, action, target_type, target_id)
  values (caller, 'session_outbound_message_set', 'session', p_session_id::text);
  return jsonb_build_object('id', p_session_id, 'saved', true);
end;
$$;
revoke all on function public.pm_set_outbound_message(bigint, text) from public, anon;
grant execute on function public.pm_set_outbound_message(bigint, text) to authenticated;

create or replace function public.accept_session(p_session_id bigint, p_scheduled_at timestamptz default null)
returns jsonb language plpgsql security definer set search_path = public as $$
declare caller uuid := auth.uid(); row public.sessions;
begin
  select * into row from public.sessions where id = p_session_id for update;
  if row.id is null then raise exception 'session_not_found'; end if;
  if row.mentor_id <> caller or row.status <> 'pending' then raise exception 'forbidden'; end if;
  update public.sessions set status = 'scheduled', scheduled_at = coalesce(p_scheduled_at, scheduled_at),
    meeting_url = coalesce(meeting_url, 'https://teams.microsoft.com/l/meetup-join/ment-demo-' || id),
    last_activity_at = now() where id = p_session_id returning * into row;
  insert into public.session_messages(session_id, sender_id, kind, body)
  values (p_session_id, caller, 'system', 'Request accepted.');
  return public.session_payload(row, caller);
end;
$$;

create or replace function public.reschedule_session(p_session_id bigint, p_scheduled_at timestamptz)
returns jsonb language plpgsql security definer set search_path = public as $$
declare caller uuid := auth.uid(); row public.sessions;
begin
  if p_scheduled_at is null or p_scheduled_at <= now() then raise exception 'invalid_schedule'; end if;
  select * into row from public.sessions where id = p_session_id for update;
  if row.id is null then raise exception 'session_not_found'; end if;
  if caller not in (row.mentor_id, row.mentee_id) or row.status <> 'scheduled' then raise exception 'forbidden'; end if;
  update public.sessions set scheduled_at = p_scheduled_at,
    meeting_url = coalesce(meeting_url, 'https://teams.microsoft.com/l/meetup-join/ment-demo-' || id),
    last_activity_at = now() where id = p_session_id returning * into row;
  insert into public.session_messages(session_id, sender_id, kind, body)
  values (p_session_id, caller, 'schedule', 'Meeting scheduled for ' || to_char(p_scheduled_at at time zone 'UTC', 'Mon DD, YYYY HH24:MI') || ' UTC.');
  return public.session_payload(row, caller);
end;
$$;

create or replace function public.cancel_session(p_session_id bigint, p_status text default 'cancelled')
returns jsonb language plpgsql security definer set search_path = public as $$
declare caller uuid := auth.uid(); row public.sessions;
begin
  if p_status not in ('declined', 'cancelled') then raise exception 'invalid_status'; end if;
  select * into row from public.sessions where id = p_session_id for update;
  if row.id is null then raise exception 'session_not_found'; end if;
  if caller not in (row.mentor_id, row.mentee_id) then raise exception 'forbidden'; end if;
  update public.sessions set status = p_status, last_activity_at = now() where id = p_session_id returning * into row;
  insert into public.session_messages(session_id, sender_id, kind, body)
  values (p_session_id, caller, 'system', case when p_status = 'declined' then 'Request declined.' else 'Meeting cancelled.' end);
  return public.session_payload(row, caller);
end;
$$;

revoke all on function public.accept_session(bigint, timestamptz), public.reschedule_session(bigint, timestamptz), public.cancel_session(bigint, text) from public, anon;
grant execute on function public.accept_session(bigint, timestamptz), public.reschedule_session(bigint, timestamptz), public.cancel_session(bigint, text) to authenticated;
