create table if not exists public.session_messages (
  id bigint generated by default as identity primary key,
  session_id bigint not null references public.sessions(id) on delete cascade,
  sender_id uuid references public.profiles(id) on delete set null,
  kind text not null default 'message' check (kind in ('request', 'message', 'system', 'schedule')),
  body text not null check (char_length(trim(body)) between 1 and 6000),
  created_at timestamptz not null default now()
);

create index if not exists session_messages_thread
  on public.session_messages(session_id, created_at, id);
create unique index if not exists session_messages_one_request
  on public.session_messages(session_id) where kind = 'request';

alter table public.session_messages enable row level security;
revoke all on public.session_messages from public, anon, authenticated;
grant select on public.session_messages to authenticated;
grant all on public.session_messages to service_role;

drop policy if exists session_messages_participants on public.session_messages;
create policy session_messages_participants on public.session_messages
  for select to authenticated using (
    exists (
      select 1 from public.sessions s
      where s.id = session_id and auth.uid() in (s.mentor_id, s.mentee_id)
    )
  );

insert into public.session_messages(session_id, sender_id, kind, body, created_at)
select s.id, s.mentee_id, 'request', s.outbound_message, s.created_at
from public.sessions s
where nullif(trim(s.outbound_message), '') is not null
  and not exists (
    select 1 from public.session_messages m where m.session_id = s.id and m.kind = 'request'
  );

