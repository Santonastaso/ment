create or replace function public.peer_linkedin(p_user_id uuid)
returns jsonb language plpgsql stable security definer set search_path = public as $$
declare caller uuid := auth.uid(); caller_org uuid; target public.profiles;
begin
  if caller is null then raise exception 'auth_required'; end if;
  select organization_id into caller_org from public.profiles where id = caller;
  select * into target from public.profiles where id = p_user_id and deactivated_at is null;
  if target.id is null or (target.organization_id is distinct from caller_org and not public.is_platform_admin(caller)) then
    raise exception 'not_found';
  end if;
  return jsonb_build_object('linkedin_url', target.linkedin_url, 'linkedin_headline', target.linkedin_headline);
end;
$$;
