create or replace function public.my_session_messages(p_session_id bigint)
returns jsonb language plpgsql stable security definer set search_path = public as $$
declare caller uuid := auth.uid();
begin
  if not exists (select 1 from public.sessions s where s.id = p_session_id and caller in (s.mentor_id, s.mentee_id)) then
    raise exception 'not_found';
  end if;
  return coalesce((select jsonb_agg(jsonb_build_object(
    'id', m.id, 'session_id', m.session_id, 'sender_id', m.sender_id,
    'kind', m.kind, 'body', m.body, 'created_at', m.created_at
  ) order by m.created_at, m.id) from public.session_messages m where m.session_id = p_session_id), '[]'::jsonb);
end;
$$;
revoke all on function public.my_session_messages(bigint) from public, anon;
