create or replace function public.is_currently_available_mentor(p_user_id uuid)
returns boolean language sql stable set search_path = public as $$
  select coalesce(
    not p.mentorship_paused
    and (p.mentorship_unavailable_until is null or p.mentorship_unavailable_until <= current_date)
    and not exists (
      select 1 from public.mentorship_unavailable_periods up
      where up.user_id = p.id and current_date between up.start_date and up.end_date
    )
    and (
      select count(*) from public.sessions s
      where s.mentor_id = p.id and s.status in ('scheduled', 'completed')
        and coalesce(s.scheduled_at, s.accepted_at, s.created_at) >= date_trunc('week', now())
        and coalesce(s.scheduled_at, s.accepted_at, s.created_at) < date_trunc('week', now()) + interval '1 week'
    ) < p.weekly_meeting_limit
    and (
      select count(*) from public.sessions s
      where s.mentor_id = p.id and s.status in ('scheduled', 'completed')
        and coalesce(s.scheduled_at, s.accepted_at, s.created_at) >= date_trunc('month', now())
        and coalesce(s.scheduled_at, s.accepted_at, s.created_at) < date_trunc('month', now()) + interval '1 month'
    ) < p.monthly_meeting_limit,
    false
  )
  from public.profiles p where p.id = p_user_id
$$;
grant execute on function public.is_currently_available_mentor(uuid) to authenticated;

create or replace function public.directory_browse(
  p_limit integer default 12, p_offset integer default 0, p_persona text default null,
  p_program text default null, p_cohort_year integer default null, p_location text default null,
  p_working_language text default null, p_query text default null
)
returns jsonb language plpgsql stable security definer set search_path = public as $$
declare
  viewer uuid := auth.uid(); viewer_org uuid; org_type text; inter_org boolean;
  query_text text; persona_filter text; result jsonb;
begin
  if viewer is null then raise exception 'auth_required'; end if;
  select organization_id into viewer_org from public.profiles where id = viewer;
  select coalesce(o.type, 'intra') into org_type from public.organizations o where o.id = viewer_org;
  inter_org := org_type = 'inter';
  query_text := nullif(trim(coalesce(p_query, '')), '');
  persona_filter := case when p_persona in ('student', 'alumnus') then p_persona else null end;

  with eligible as (
    select p.* from public.profiles p
    where p.organization_id = viewer_org and p.id <> viewer and p.admin_scope = 'none'
      and p.onboarding_complete and p.deactivated_at is null
      and public.is_currently_available_mentor(p.id)
  ), filtered as (
    select e.* from eligible e
    where (persona_filter is null or e.role = persona_filter)
      and (p_program is null or e.program = p_program)
      and (p_cohort_year is null or e.cohort_year = p_cohort_year)
      and (p_location is null or e.location = p_location)
      and (p_working_language is null or e.working_language = p_working_language)
      and (query_text is null or e.name ilike '%' || query_text || '%'
        or coalesce(e.job_title, '') ilike '%' || query_text || '%'
        or coalesce(e.program, '') ilike '%' || query_text || '%'
        or coalesce(e.department, '') ilike '%' || query_text || '%'
        or coalesce(e.bio, '') ilike '%' || query_text || '%'
        or exists (select 1 from public.skills s where s.user_id = e.id and s.type = 'can_teach' and s.skill ilike '%' || query_text || '%'))
  ), page as (
    select f.* from filtered f order by lower(f.name), f.id
    limit least(greatest(coalesce(p_limit, 12), 1), 50) offset greatest(coalesce(p_offset, 0), 0)
  ), people_json as (
    select jsonb_build_object(
      'id', pg.id, 'name', case when inter_org then public.redacted_name(pg.name) else pg.name end,
      'role', pg.role, 'department', pg.department, 'program', pg.program,
      'cohort_year', pg.cohort_year, 'job_title', case when inter_org then null else pg.job_title end,
      'current_role', case when inter_org then null else pg.job_title end,
      'location', case when inter_org then null else pg.location end,
      'working_language', pg.working_language, 'bio', pg.bio, 'mentorship_available', true,
      'skills', coalesce((select jsonb_agg(jsonb_build_object('skill', s.skill, 'type', s.type) order by lower(s.skill))
        from public.skills s where s.user_id = pg.id and s.type = 'can_teach'), '[]'::jsonb)
    ) as item from page pg
  ), facets as (
    select
      (select coalesce(jsonb_agg(v order by v), '[]'::jsonb) from (select distinct program v from eligible where coalesce(program, '') <> '') x) programs,
      (select coalesce(jsonb_agg(v order by v), '[]'::jsonb) from (select distinct location v from eligible where coalesce(location, '') <> '') x) locations,
      (select coalesce(jsonb_agg(v order by v), '[]'::jsonb) from (select distinct working_language v from eligible) x) languages,
      (select coalesce(jsonb_agg(v order by v desc), '[]'::jsonb) from (select distinct cohort_year v from eligible where cohort_year is not null) x) cohort_years
  )
  select jsonb_build_object(
    'total', (select count(*) from filtered)::int,
    'people', (select coalesce(jsonb_agg(item), '[]'::jsonb) from people_json),
    'facets', jsonb_build_object('programs', f.programs, 'locations', f.locations, 'languages', f.languages, 'cohortYears', f.cohort_years)
  ) into result from facets f;
  return result;
end;
$$;
grant execute on function public.directory_browse(integer, integer, text, text, integer, text, text, text) to authenticated;

create or replace function public.my_meeting_capacity()
returns jsonb language plpgsql stable security definer set search_path = public as $$
declare
  caller uuid := auth.uid(); weekly_limit integer; monthly_limit integer;
  weekly_booked integer; monthly_booked integer;
begin
  if caller is null then raise exception 'auth_required'; end if;
  select p.weekly_meeting_limit, p.monthly_meeting_limit into weekly_limit, monthly_limit
  from public.profiles p where p.id = caller;
  select count(*) into weekly_booked from public.sessions s
  where s.mentor_id = caller and s.status in ('scheduled', 'completed')
    and coalesce(s.scheduled_at, s.accepted_at, s.created_at) >= date_trunc('week', now())
    and coalesce(s.scheduled_at, s.accepted_at, s.created_at) < date_trunc('week', now()) + interval '1 week';
  select count(*) into monthly_booked from public.sessions s
  where s.mentor_id = caller and s.status in ('scheduled', 'completed')
    and coalesce(s.scheduled_at, s.accepted_at, s.created_at) >= date_trunc('month', now())
    and coalesce(s.scheduled_at, s.accepted_at, s.created_at) < date_trunc('month', now()) + interval '1 month';
  return jsonb_build_object(
    'weekly_limit', weekly_limit, 'monthly_limit', monthly_limit,
    'weekly_booked', weekly_booked, 'monthly_booked', monthly_booked,
    'available', weekly_booked < weekly_limit and monthly_booked < monthly_limit
  );
end;
$$;
revoke all on function public.my_meeting_capacity() from public, anon;
grant execute on function public.my_meeting_capacity() to authenticated;

create or replace function public.enforce_meeting_capacity()
returns trigger language plpgsql security definer set search_path = public as $$
declare
  weekly_limit integer; monthly_limit integer; weekly_booked integer; monthly_booked integer;
  meeting_time timestamptz := coalesce(new.scheduled_at, now());
begin
  if new.status <> 'scheduled' then return new; end if;
  if tg_op = 'UPDATE' and old.status = new.status and old.scheduled_at is not distinct from new.scheduled_at then return new; end if;
  select p.weekly_meeting_limit, p.monthly_meeting_limit into weekly_limit, monthly_limit
  from public.profiles p where p.id = new.mentor_id for update;
  select count(*) into weekly_booked from public.sessions s
  where s.mentor_id = new.mentor_id and s.id <> new.id and s.status in ('scheduled', 'completed')
    and coalesce(s.scheduled_at, s.accepted_at, s.created_at) >= date_trunc('week', meeting_time)
    and coalesce(s.scheduled_at, s.accepted_at, s.created_at) < date_trunc('week', meeting_time) + interval '1 week';
  select count(*) into monthly_booked from public.sessions s
  where s.mentor_id = new.mentor_id and s.id <> new.id and s.status in ('scheduled', 'completed')
    and coalesce(s.scheduled_at, s.accepted_at, s.created_at) >= date_trunc('month', meeting_time)
    and coalesce(s.scheduled_at, s.accepted_at, s.created_at) < date_trunc('month', meeting_time) + interval '1 month';
  if weekly_booked >= weekly_limit then raise exception 'weekly_capacity_reached'; end if;
  if monthly_booked >= monthly_limit then raise exception 'monthly_capacity_reached'; end if;
  return new;
end;
$$;
revoke all on function public.enforce_meeting_capacity() from public, anon, authenticated;

